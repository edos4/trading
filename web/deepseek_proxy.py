"""Serve the DeepSeek Harness (``dsh``) Web UI same-origin at ``/deepseek``.

DeepSeek Harness ships its own browser UI on a loopback port (3080 by
default). Bound to loopback it trusts every caller it can reach, and this app
already authenticates the operator, so the UI is proxied here rather than
linked out to — same-origin, under the existing login, so it also works
through the HTTPS tunnel.

dsh's own deployment contract decides what this proxy must do
(https://deepseek-harness.github.io/deepseek-harness/en/guide/public-deployments):

* **Preserve the browser-facing ``Host``.** The harness fences every request
  against its accepted authorities and mints its session cookie bound to the
  authority it was reached by, so ``--trusted-host`` must name the authority
  the browser uses and this proxy must not rewrite ``Host`` to the listener's.
* **Strip the mount prefix.** The listener only ever serves origin-root
  routes, so ``/deepseek/api/...`` must arrive upstream as ``/api/...``.
* **Forward upgrades.** Session traffic rides a WebSocket
  (``/api/remote.mux``), so HTTP and WS both have to reach the listener.
* **Rewrite cookie scope.** The listener serves plain loopback HTTP, so it
  issues host-only ``Path=/`` cookies with no ``Secure``; here the cookie is
  narrowed to the mount and marked ``Secure`` when the browser leg is HTTPS.
* **Sign in for the browser.** Each process mints a random *launch token* and
  exchanges it — on ``GET /?token=…`` only — for the signed session cookie.
  The token is printed at startup and written to a file by the launcher, so a
  browser that arrives with no cookie (first visit, or after the 30-day cookie
  expired) is signed in transparently instead of ever seeing the credential.

Only authenticated callers are forwarded: the harness is a full agent that
reads and writes the workspace and runs commands, so it is never served
anonymously.
"""
from __future__ import annotations

import asyncio
import threading
from pathlib import Path
from urllib.parse import quote

import httpx
from starlette.requests import HTTPConnection, Request
from starlette.responses import JSONResponse, Response

from utils.logger import log

#: Mount point. ``/deepseek`` itself is the UI tab page; ``/deepseek/`` and
#: below belong to the harness.
PREFIX = "/deepseek"

#: Only the connect leg of an upstream call is bounded: an agent turn can
#: stream for minutes, and a buffered request body is already in hand.
_CONNECT_TIMEOUT = 15.0


class _ListenerClient:
    """HTTP client for the harness with no cookie jar of its own.

    Cookies belong to the browser: this forwards whatever ``Cookie`` header the
    browser sent and hands any ``Set-Cookie`` straight back, so nobody's session
    is stored proxy-side and no request is authenticated by someone else's.
    """

    def __init__(self) -> None:
        self._transport = httpx.AsyncHTTPTransport()

    async def request(self, method: str, url: str, *, content=None,
                      headers=None) -> httpx.Response:
        request = httpx.Request(method, url, content=content, headers=headers)
        request.extensions["timeout"] = {"connect": _CONNECT_TIMEOUT}
        response = await self._transport.handle_async_request(request)
        await response.aread()
        return response


#: Re-derived by the client library; forwarding them corrupts the body.
#: ``Host`` is deliberately *kept*: the harness fences every request on
#: Host/Origin and mints its cookie against the authority it was reached by, so
#: rewriting it to the listener's address would 403 every browser call.
_DROP_REQUEST_HEADERS = frozenset({
    "content-length", "connection", "accept-encoding", "transfer-encoding",
})
_DROP_RESPONSE_HEADERS = frozenset({
    "content-length", "content-encoding", "transfer-encoding", "connection",
})

#: The handshake headers are regenerated by the client library for the upstream
#: connection; forwarding the browser's copies duplicates Sec-WebSocket-Key and
#: friends, which the server answers with HTTP 400 — and ``Host`` is *not*
#: forwardable at all: an explicit Host is appended rather than substituted, and
#: two Host headers fail the harness fence with HTTP 403. The browser authority
#: travels as the connect URI's authority instead (see ``_forward_ws``).
_DROP_WS_HEADERS = _DROP_REQUEST_HEADERS | frozenset({
    "upgrade", "host", "sec-websocket-key", "sec-websocket-version",
    "sec-websocket-extensions", "sec-websocket-protocol",
})

#: The session cookie dsh mints travels in this header.
_SET_COOKIE = "set-cookie"


def proxyable(path: str) -> bool:
    """True for ``/deepseek/`` and below (the bare path is our tab page)."""
    return path == PREFIX + "/" or path.startswith(PREFIX + "/")


def upstream_path(path: str, query: str = "") -> str:
    """Strip the mount prefix: ``/deepseek/api/x`` -> ``/api/x``."""
    stripped = path[len(PREFIX):] or "/"
    if not stripped.startswith("/"):
        stripped = "/" + stripped
    if query:
        stripped = f"{stripped}?{query}"
    return stripped


def rewrite_location(location: str) -> str:
    """Keep redirects inside the mount (``/login`` -> ``/deepseek/login``).

    dsh's launch exchange answers ``location: ./``; a relative target already
    resolves against the mount and is left alone.
    """
    if not location.startswith("/") or location.startswith("//"):
        return location
    if location == PREFIX or location.startswith(PREFIX + "/"):
        return location
    return PREFIX + location


def rewrite_set_cookie(value: str, *, secure: bool) -> str:
    """Narrow a harness cookie to the mount and mark it ``Secure`` on HTTPS.

    The listener serves loopback HTTP, so its cookies are host-wide
    (``Path=/``) and unmarked. Left alone they would ride every request this
    origin serves; scoped to ``/deepseek/`` they only ever come back here.
    """
    parts = [part.strip() for part in value.split(";")]
    head, attributes = parts[0], parts[1:]
    kept: list[str] = []
    marked_secure = False
    for attribute in attributes:
        name = attribute.split("=", 1)[0].strip().lower()
        if name == "path":
            kept.append(f"Path={PREFIX}/")
            continue
        if name == "secure":
            marked_secure = True
        kept.append(attribute)
    if secure and not marked_secure:
        kept.append("Secure")
    return "; ".join([head, *kept])


def forwarded_ws_headers(raw_headers) -> list[tuple[str, str]]:
    """Headers to carry onto the upstream WebSocket, minus the handshake ones."""
    headers: list[tuple[str, str]] = []
    for key, value in raw_headers:
        name = key.decode()
        if name.lower() in _DROP_WS_HEADERS:
            continue
        headers.append((name, value.decode()))
    return headers


def is_document(request: Request) -> bool:
    """True for a navigation/document fetch, which is what the token signs in."""
    accept = request.headers.get("accept", "")
    return "text/html" in accept or request.headers.get("sec-fetch-mode") == "navigate"


class _LaunchToken:
    """The harness's per-process launch token, re-read when its file changes."""

    def __init__(self, path: str | None) -> None:
        self._path = Path(path) if path else None
        self._lock = threading.Lock()
        self._stamp: tuple[float, int] | None = None
        self._token: str | None = None

    def get(self) -> str | None:
        if self._path is None:
            return None
        try:
            stat = self._path.stat()
            stamp = (stat.st_mtime, stat.st_size)
        except OSError:
            with self._lock:
                self._stamp, self._token = None, None
            return None
        with self._lock:
            if self._stamp != stamp:
                self._token = self._read()
                self._stamp = stamp
            return self._token

    def _read(self) -> str | None:
        path = self._path
        if path is None:  # pragma: no cover - get() already guards this
            return None
        try:
            token = path.read_text(encoding="utf-8").strip()
        except OSError:
            return None
        return token or None


class DeepSeekHarnessProxy:
    """ASGI middleware: forward ``/deepseek/*`` (HTTP and WebSocket) upstream."""

    def __init__(self, app):
        self.app = app
        self._lock = threading.Lock()
        self._client: _ListenerClient | None = None
        self._loop: asyncio.AbstractEventLoop | None = None
        self._tokens: dict[str, _LaunchToken] = {}

    async def __call__(self, scope, receive, send) -> None:
        if not self._should_proxy(scope):
            return await self.app(scope, receive, send)
        if not self._authenticated(HTTPConnection(scope)):
            # Never forward anonymously: the harness can edit the workspace and
            # run commands. Answer exactly as a protected local route would.
            return await self._deny(scope, receive, send)
        if scope["type"] == "websocket":
            return await self._forward_ws(scope, receive, send)
        return await self._forward_http(scope, receive, send)

    # ── gating ───────────────────────────────────────────────────────────
    def _should_proxy(self, scope) -> bool:
        if scope.get("type") not in ("http", "websocket"):
            return False
        if not self._enabled():
            return False
        return proxyable(scope.get("path", ""))

    @staticmethod
    def _enabled() -> bool:
        from config import settings

        return bool((settings.deepseek_harness_url or "").strip())

    @staticmethod
    def _authenticated(connection: HTTPConnection) -> bool:
        """The same decision ``require_login`` makes, without the dependency."""
        from web.auth import current_username, username_from_basic_auth

        return bool(
            current_username(connection) or username_from_basic_auth(connection)
        )

    @staticmethod
    async def _deny(scope, receive, send) -> None:
        """Reject an anonymous caller the way a protected route would."""
        if scope["type"] == "websocket":
            await send({"type": "websocket.close", "code": 4401})
            return
        from fastapi import HTTPException

        from web.auth import require_login

        try:
            await require_login(Request(scope, receive))
        except HTTPException as exc:  # HTML navigation -> 303 /api -> 401
            response = Response(status_code=exc.status_code, headers=exc.headers or {})
        else:  # pragma: no cover - require_login only returns when authenticated
            response = Response(status_code=401)
        await response(scope, receive, send)

    # ── HTTP ─────────────────────────────────────────────────────────────
    def _upstream(self):
        """A pooled, deliberately cookie-less client for the harness listener.

        Not ``httpx.AsyncClient``: its cookie jar files any Set-Cookie the
        harness sends under the *listener's* host and replays it on later
        requests — so one browser's sign-in would silently authenticate every
        other request, and the browser that should have received the session
        cookie would never see it. A transport keeps the pool and drops the jar.
        """
        loop = asyncio.get_running_loop()
        with self._lock:
            # A transport's pool is bound to the loop that made it, so it is
            # re-created when the loop changes (a production server keeps one
            # loop; in-process test clients hand each request a fresh one).
            if self._client is None or self._loop is not loop:
                self._client = _ListenerClient()
                self._loop = loop
            return self._client

    def _launch_token(self) -> str | None:
        from config import settings

        path = (settings.deepseek_harness_token_file or "").strip()
        if not path:
            return None
        with self._lock:
            return self._tokens.setdefault(path, _LaunchToken(path)).get()

    def _forward_headers(self, request: Request) -> dict[str, str]:
        headers = {
            key: value
            for key, value in request.headers.items()
            if key.lower() not in _DROP_REQUEST_HEADERS
        }
        # The harness fences on Host/Origin, so the browser-facing authority is
        # forwarded untouched rather than rewritten to the listener's.
        headers["x-forwarded-prefix"] = PREFIX
        from web.auth import request_is_https

        headers["x-forwarded-proto"] = "https" if request_is_https(request) else "http"
        headers["x-forwarded-host"] = request.headers.get("host", "")
        return headers

    async def _forward_http(self, scope, receive, send) -> None:
        request = Request(scope, receive)
        target = upstream_path(scope["path"], scope.get("query_string", b"").decode())
        body = await request.body()
        headers = self._forward_headers(request)
        secure = headers["x-forwarded-proto"] == "https"
        try:
            upstream = await self._upstream().request(
                request.method, self._listener_url(target),
                content=body or None, headers=headers,
            )
            if upstream.status_code == 401 and is_document(request):
                # No session cookie yet: replay the launch token for the
                # browser instead of showing it a 401.
                upstream = await self._sign_in(headers) or upstream
        except Exception as exc:
            log.warning(f"DeepSeek harness | proxy {target} failed: "
                        f"{type(exc).__name__}: {exc}")
            response = JSONResponse(
                {"detail": "DeepSeek harness unreachable; check "
                           "DEEPSEEK_HARNESS_URL"},
                status_code=503,
            )
            return await response(scope, receive, send)
        response = self._build_response(upstream, secure=secure)
        await response(scope, receive, send)

    @staticmethod
    def _listener_url(target: str) -> str:
        from config import settings

        return settings.deepseek_harness_url.rstrip("/") + target

    async def _sign_in(self, headers: dict[str, str]) -> httpx.Response | None:
        """Exchange the launch token for the harness session cookie.

        The token is accepted on ``GET /?token=…`` only, and *that* response is
        what sets the cookie — so the harness, not this proxy, answers the
        browser, and the browser keeps holding its own session.
        """
        token = self._launch_token()
        if not token:
            log.warning("DeepSeek harness | unauthenticated document request and "
                        "no launch token available; set "
                        "DEEPSEEK_HARNESS_TOKEN_FILE")
            return None
        try:
            url = f"{self._listener_url('/')}?token={quote(token, safe='')}"
            return await self._upstream().request("GET", url, headers=headers)
        except Exception as exc:
            log.warning(f"DeepSeek harness | launch token exchange failed: "
                        f"{type(exc).__name__}: {exc}")
            return None

    @staticmethod
    def _build_response(upstream: httpx.Response, *, secure: bool) -> Response:
        raw: list[tuple[bytes, bytes]] = []
        for key, value in upstream.headers.multi_items():
            low = key.lower()
            if low in _DROP_RESPONSE_HEADERS:
                continue
            if low == "location":
                value = rewrite_location(value)
            elif low == _SET_COOKIE:
                value = rewrite_set_cookie(value, secure=secure)
            raw.append((low.encode("latin-1"), value.encode("latin-1")))
        # Starlette re-derives content-length from the body, which is what we
        # want after httpx decoded the upstream encoding. Raw headers are used
        # so multiple Set-Cookie values survive (a dict would collapse them).
        if upstream.status_code >= 200 and upstream.status_code not in (204, 304):
            raw.append((b"content-length", str(len(upstream.content)).encode("latin-1")))
        response = Response(content=upstream.content, status_code=upstream.status_code)
        response.raw_headers = raw
        return response

    # ── WebSocket (the harness session mux: /api/remote.mux) ─────────────
    async def _forward_ws(self, scope, receive, send) -> None:
        listen_host, listen_port = self._ws_target()
        target = upstream_path(scope["path"], scope.get("query_string", b"").decode())
        raw = {k.decode().lower(): v.decode() for k, v in scope.get("headers", [])}
        headers = forwarded_ws_headers(scope.get("headers", []))
        # The handshake's Host comes from the URI, not from a header: the client
        # library *appends* an explicit Host instead of replacing its own, and
        # two Host headers fail the harness fence with 403. So the request is
        # addressed to the browser's authority and the connection is pointed at
        # the listener separately — Host, Origin and the authority-bound session
        # cookie then all agree, which is what the fence checks.
        browser_host = raw.get("host") or f"{listen_host}:{listen_port}"
        ws_uri = f"ws://{browser_host}{target}"

        import websockets

        try:
            async with websockets.connect(
                ws_uri,
                host=listen_host,
                port=listen_port,
                additional_headers=headers,
                subprotocols=scope.get("subprotocols") or None,
            ) as upstream:
                await send({
                    "type": "websocket.accept",
                    "subprotocol": upstream.subprotocol,
                })
                await self._pump(receive, send, upstream)
        except Exception as exc:
            log.warning(f"DeepSeek harness | ws {target} failed: "
                        f"{type(exc).__name__}: {exc}")
            try:
                await send({"type": "websocket.close", "code": 1011})
            except Exception:
                pass

    @staticmethod
    def _ws_target() -> tuple[str, int]:
        """(host, port) of the listener the upstream WS connection is made to."""
        from urllib.parse import urlsplit

        from config import settings

        parts = urlsplit(settings.deepseek_harness_url)
        return (
            parts.hostname or "127.0.0.1",
            parts.port or (443 if parts.scheme == "https" else 80),
        )

    @staticmethod
    async def _pump(receive, send, upstream) -> None:
        import websockets

        async def client_to_upstream() -> None:
            while True:
                message = await receive()
                if message["type"] == "websocket.receive":
                    if message.get("text") is not None:
                        await upstream.send(message["text"])
                    elif message.get("bytes") is not None:
                        await upstream.send(message["bytes"])
                elif message["type"] == "websocket.disconnect":
                    await upstream.close()
                    return

        async def upstream_to_client() -> None:
            try:
                async for message in upstream:
                    if isinstance(message, bytes):
                        await send({"type": "websocket.send", "bytes": message})
                    else:
                        await send({"type": "websocket.send", "text": message})
            except websockets.exceptions.ConnectionClosed:
                pass

        tasks = [
            asyncio.create_task(client_to_upstream()),
            asyncio.create_task(upstream_to_client()),
        ]
        try:
            await asyncio.wait(tasks, return_when=asyncio.FIRST_COMPLETED)
        finally:
            for task in tasks:
                task.cancel()
            try:
                await send({"type": "websocket.close", "code": 1000})
            except Exception:
                pass
