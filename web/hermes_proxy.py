"""Serve the Hermes Agent web dashboard same-origin at ``/hermes``.

Hermes ships a browser dashboard (a React SPA behind FastAPI) on
``http://127.0.0.1:9119``. Bound to loopback it carries no auth of its own, and
this app already authenticates the operator, so the dashboard is proxied here
rather than linked out to. Same-origin is not a preference, it is a
requirement:

* the SPA builds **root-absolute** asset URLs (``/assets/…``), and
* over the Cloudflare tunnel this page is HTTPS, so an ``http://127.0.0.1``
  iframe would be blocked as mixed content — and in a remote browser
  ``127.0.0.1`` is the *client's* loopback, not this host's.

The upstream SPA honours ``X-Forwarded-Prefix`` (verified: it sets
``window.__HERMES_BASE_PATH__`` from it), which is what makes it emit
``/hermes/…`` asset and API URLs. The prefix is stripped before forwarding, so
``/hermes/assets/app.js`` reaches ``/assets/app.js`` upstream.

One wrinkle the prefix cannot fix: the SPA's code-split chunks and CSS are
compiled by Vite with ``base: "/"``, so at runtime it requests them from the
origin **root** (``/assets/…``) even though the page is mounted under the
prefix. Those requests would hit this app instead. They are forwarded too —
``/assets/`` is not used by anything else here, and only the mounted dashboard
ever asks for it. Without this, any lazy-loaded route (the Chat tab, for one)
404s its chunk and the page goes blank.

Only authenticated callers are forwarded. An anonymous request falls through to
the app, which answers with its own 401 / login redirect — the dashboard's admin
surface (it reads and writes ``~/.hermes/.env`` and can run agent commands) is
never served anonymously.
"""
from __future__ import annotations

import asyncio
import threading

import httpx
from starlette.requests import HTTPConnection, Request
from starlette.responses import JSONResponse, Response

from utils.logger import log

#: Mount point. ``/hermes`` itself is the UI tab page; ``/hermes/`` and below
#: belong to the dashboard.
PREFIX = "/hermes"

#: Origin-root path the SPA's Vite-built chunks and CSS live under (see above).
ROOT_ASSET_PREFIX = "/assets/"

_PROXY_TIMEOUT = 60.0

#: Re-derived by the client library; forwarding them corrupts the body.
_DROP_REQUEST_HEADERS = frozenset({
    "host", "content-length", "connection", "accept-encoding", "transfer-encoding",
})
_DROP_RESPONSE_HEADERS = frozenset({
    "content-length", "content-encoding", "transfer-encoding", "connection",
})

#: The handshake headers are regenerated by the client library for the upstream
#: connection; forwarding the browser's copies duplicates Sec-WebSocket-Key and
#: friends, which the server answers with HTTP 400.
_DROP_WS_HEADERS = _DROP_REQUEST_HEADERS | frozenset({
    "upgrade", "sec-websocket-key", "sec-websocket-version",
    "sec-websocket-extensions", "sec-websocket-protocol",
})


def proxyable(path: str) -> bool:
    """True for ``/hermes/`` and below, plus the SPA's root ``/assets/``."""
    if path == PREFIX + "/" or path.startswith(PREFIX + "/"):
        return True
    return path.startswith(ROOT_ASSET_PREFIX)


def upstream_path(path: str, query: str = "") -> str:
    """Strip the mount prefix: ``/hermes/assets/app.js`` -> ``/assets/app.js``.

    Root ``/assets/…`` is already in upstream coordinates and passes through.
    """
    if path.startswith(ROOT_ASSET_PREFIX):
        stripped = path
    else:
        stripped = path[len(PREFIX):] or "/"
        if not stripped.startswith("/"):
            stripped = "/" + stripped
    if query:
        stripped = f"{stripped}?{query}"
    return stripped


def rewrite_location(location: str) -> str:
    """Keep redirects inside the mount (``/login`` -> ``/hermes/login``)."""
    if not location.startswith("/") or location.startswith("//"):
        return location
    if location == PREFIX or location.startswith(PREFIX + "/"):
        return location
    return PREFIX + location


def forwarded_ws_headers(raw_headers) -> list[tuple[str, str]]:
    """Headers to carry onto the upstream WebSocket, minus the handshake ones."""
    headers: list[tuple[str, str]] = []
    for key, value in raw_headers:
        name = key.decode()
        if name.lower() in _DROP_WS_HEADERS:
            continue
        headers.append((name, value.decode()))
    headers.append(("x-forwarded-prefix", PREFIX))
    return headers


class HermesDashboardProxy:
    """ASGI middleware: forward ``/hermes/*`` (HTTP and WebSocket) upstream."""

    def __init__(self, app):
        self.app = app
        self._lock = threading.Lock()
        self._client: httpx.AsyncClient | None = None
        self._origin: str | None = None
        self._loop: asyncio.AbstractEventLoop | None = None

    async def __call__(self, scope, receive, send) -> None:
        if not self._should_proxy(scope):
            return await self.app(scope, receive, send)
        if not self._authenticated(HTTPConnection(scope)):
            # Never forward anonymously: the dashboard is an admin surface that
            # reads and writes ~/.hermes/.env. Answer exactly as a protected
            # local route would, rather than a bare 404 for the missing route.
            return await self._deny(scope, receive, send)
        if scope["type"] == "websocket":
            return await self._forward_ws(scope, receive, send)
        return await self._forward_http(scope, receive, send)

    # ── gating ───────────────────────────────────────────────────────────
    def _should_proxy(self, scope) -> bool:
        if scope.get("type") not in ("http", "websocket"):
            return False
        if not self._enabled():
            return False
        return proxyable(scope.get("path", ""))

    @staticmethod
    def _enabled() -> bool:
        from config import settings

        return bool((settings.hermes_dashboard_url or "").strip())

    @staticmethod
    def _authenticated(connection: HTTPConnection) -> bool:
        """The same decision ``require_login`` makes, without the dependency."""
        from web.auth import current_username, username_from_basic_auth

        return bool(
            current_username(connection) or username_from_basic_auth(connection)
        )

    @staticmethod
    async def _deny(scope, receive, send) -> None:
        """Reject an anonymous caller the way a protected route would."""
        if scope["type"] == "websocket":
            await send({"type": "websocket.close", "code": 4401})
            return
        from fastapi import HTTPException

        from web.auth import require_login

        try:
            await require_login(Request(scope, receive))
        except HTTPException as exc:  # HTML navigation -> 303 /api -> 401
            response = Response(status_code=exc.status_code, headers=exc.headers or {})
        else:  # pragma: no cover - require_login only returns when authenticated
            response = Response(status_code=401)
        await response(scope, receive, send)

    # ── HTTP ─────────────────────────────────────────────────────────────
    def _async_client(self) -> httpx.AsyncClient:
        from config import settings

        origin = settings.hermes_dashboard_url.rstrip("/")
        # An httpx client's pool is bound to the loop that made it, so it is
        # re-created when the loop changes (a production server keeps one loop;
        # in-process test clients hand each request a fresh one).
        loop = asyncio.get_running_loop()
        with self._lock:
            if (self._client is None or self._origin != origin
                    or self._loop is not loop):
                self._client = httpx.AsyncClient(
                    base_url=origin,
                    timeout=_PROXY_TIMEOUT,
                    follow_redirects=False,
                )
                self._origin = origin
                self._loop = loop
            return self._client

    def _forward_headers(self, request: Request) -> dict[str, str]:
        headers = {
            key: value
            for key, value in request.headers.items()
            if key.lower() not in _DROP_REQUEST_HEADERS
        }
        # What makes the SPA emit /hermes-prefixed asset and API URLs.
        headers["x-forwarded-prefix"] = PREFIX
        from web.auth import request_is_https

        headers["x-forwarded-proto"] = "https" if request_is_https(request) else "http"
        headers["x-forwarded-host"] = request.headers.get("host", "")
        return headers

    async def _forward_http(self, scope, receive, send) -> None:
        request = Request(scope, receive)
        target = upstream_path(scope["path"], scope.get("query_string", b"").decode())
        body = await request.body()
        try:
            upstream = await self._async_client().request(
                request.method, target, content=body or None,
                headers=self._forward_headers(request),
            )
        except Exception as exc:
            log.warning(f"Hermes dashboard | proxy {target} failed: {type(exc).__name__}: {exc}")
            response = JSONResponse(
                {"detail": "Hermes dashboard unreachable; check HERMES_DASHBOARD_URL"},
                status_code=503,
            )
            return await response(scope, receive, send)
        response = self._build_response(upstream)
        await response(scope, receive, send)

    @staticmethod
    def _build_response(upstream: httpx.Response) -> Response:
        raw: list[tuple[bytes, bytes]] = []
        for key, value in upstream.headers.multi_items():
            low = key.lower()
            if low in _DROP_RESPONSE_HEADERS:
                continue
            if low == "location":
                value = rewrite_location(value)
            raw.append((low.encode("latin-1"), value.encode("latin-1")))
        # Starlette re-derives content-length from the body, which is what we
        # want after httpx decoded the upstream encoding. Raw headers are used
        # so multiple Set-Cookie values survive (a dict would collapse them).
        if upstream.status_code >= 200 and upstream.status_code not in (204, 304):
            raw.append((b"content-length", str(len(upstream.content)).encode("latin-1")))
        response = Response(content=upstream.content, status_code=upstream.status_code)
        response.raw_headers = raw
        return response

    # ── WebSocket (the dashboard's embedded Chat tab: /api/pty, /api/ws) ──
    async def _forward_ws(self, scope, receive, send) -> None:
        from config import settings

        origin = settings.hermes_dashboard_url.rstrip("/")
        ws_origin = origin.replace("https://", "wss://").replace("http://", "ws://")
        target = upstream_path(scope["path"], scope.get("query_string", b"").decode())
        headers = forwarded_ws_headers(scope.get("headers", []))

        import websockets

        try:
            async with websockets.connect(
                ws_origin + target,
                additional_headers=headers,
                subprotocols=scope.get("subprotocols") or None,
            ) as upstream:
                await send({
                    "type": "websocket.accept",
                    "subprotocol": upstream.subprotocol,
                })
                await self._pump(receive, send, upstream)
        except Exception as exc:
            log.warning(f"Hermes dashboard | ws {target} failed: {type(exc).__name__}: {exc}")
            try:
                await send({"type": "websocket.close", "code": 1011})
            except Exception:
                pass

    @staticmethod
    async def _pump(receive, send, upstream) -> None:
        import websockets

        async def client_to_upstream() -> None:
            while True:
                message = await receive()
                if message["type"] == "websocket.receive":
                    if message.get("text") is not None:
                        await upstream.send(message["text"])
                    elif message.get("bytes") is not None:
                        await upstream.send(message["bytes"])
                elif message["type"] == "websocket.disconnect":
                    await upstream.close()
                    return

        async def upstream_to_client() -> None:
            try:
                async for message in upstream:
                    if isinstance(message, bytes):
                        await send({"type": "websocket.send", "bytes": message})
                    else:
                        await send({"type": "websocket.send", "text": message})
            except websockets.exceptions.ConnectionClosed:
                pass

        tasks = [
            asyncio.create_task(client_to_upstream()),
            asyncio.create_task(upstream_to_client()),
        ]
        try:
            await asyncio.wait(tasks, return_when=asyncio.FIRST_COMPLETED)
        finally:
            for task in tasks:
                task.cancel()
            try:
                await send({"type": "websocket.close", "code": 1000})
            except Exception:
                pass
